/**
 * Email domains that belong to a consumer mailbox provider rather than to one organization.
 *
 * This is the difference between "everyone at this domain is a colleague" and "everyone at this
 * domain is a stranger". An organization is keyed on `organization.domain`, so treating a provider
 * domain as a company pools unrelated people into one organization, as its owners, able to see each
 * other's applications - and, since the Members page shows contact details, each other's names and
 * email addresses.
 *
 * That is not hypothetical: this list held only `gmail.com` for months, and an `Outlook` organization
 * accumulated three unrelated people that way.
 *
 * ## This list is a floor, not the mechanism
 *
 * It cannot be made complete, and not only because there are tens of thousands of providers. Two
 * cases are impossible for *any* denylist to catch:
 *
 * - **A personal domain that looks corporate.** Proton, Fastmail and iCloud+ all let an individual
 *   attach their own domain, so `tom@piaggio.dev` is one person's mailbox that no list can recognise.
 * - **A shared domain that is not a mailbox provider.** A university pools thousands of unrelated
 *   people behind `@stanford.edu`; so does an ISP, a coworking space, or a country's civil service.
 *
 * The failure is also asymmetric, which is what makes the guess dangerous rather than merely wrong:
 * missing a provider **pools strangers** into one organization and exposes their details, while
 * wrongly listing a company only **splits colleagues**, who can invite each other. A mechanism that
 * has to guess should therefore lean towards "separate", and this one leans the other way - it
 * auto-joins unless it recognises the domain.
 *
 * The two ways out, neither of which is a longer list:
 *
 * 1. **Don't auto-join an unverified domain at all.** Give every signup its own organization and make
 *    domain capture something an organization opts into after proving control of the domain (a DNS
 *    record), which is what Slack, Notion, Linear and Vercel do. Then this list stops being a safety
 *    control.
 * 2. **Ask the identity provider instead of guessing.** Google sends the `hd` claim only for a
 *    Workspace-managed domain, and Microsoft's `tid` is the consumer tenant
 *    `9188040d-6c67-4c5b-b112-36a304b66dad` for a personal account. Those are positive assertions of
 *    exactly the fact we are trying to infer. `auth.ts` already decodes `hd`; it just isn't threaded
 *    to where the organization is chosen.
 *
 * Until then: entries here are the well-known providers, and anything not listed is treated as a
 * company domain.
 */
