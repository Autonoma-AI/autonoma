/**
 * Whether this email domain is a consumer mailbox provider, meaning two accounts sharing it are
 * strangers rather than colleagues.
 *
 * Exported as a predicate rather than the set so no caller can iterate it, mutate it, or re-derive a
 * partial copy - the membership question is the only thing anyone needs to ask. Case and surrounding
 * whitespace are normalized here, because the domains arrive from an identity provider unnormalised.
 */
export function isConsumerEmailDomain(domain: string): boolean {
    return CONSUMER_EMAIL_DOMAINS.has(domain.trim().toLowerCase());
}
